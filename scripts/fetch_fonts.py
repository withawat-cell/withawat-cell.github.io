"""Download the site's web fonts from Google Fonts and self-host them.

    python scripts/fetch_fonts.py

Fetches Inter and IBM Plex Mono (both under the SIL Open Font License 1.1), saves
the woff2 files in assets/fonts/ and rewrites the @font-face block between the
FONTS:START and FONTS:END comments in assets/css/style.css so it points at them.

Why self-host: the pages no longer wait on Google's stylesheet or open two extra
server connections, and no visitor data goes to Google. Each font is split by
unicode-range exactly as Google serves it, so a browser only downloads the Greek or
Latin-extended file on a page that actually contains those characters.

Run it again only to change fonts or subsets (edit FAMILIES below). Needs network.
"""
import os
import re
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_DIR = os.path.join(ROOT, "assets", "fonts")
CSS_PATH = os.path.join(ROOT, "assets", "css", "style.css")

# what to request, and which unicode-range subsets to keep
GOOGLE_URL = "https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600&family=IBM+Plex+Mono:wght@400;500&display=swap"
KEEP = {"Inter": ("latin", "latin-ext", "greek"), "IBM Plex Mono": ("latin", "latin-ext")}
# a current browser User-Agent makes Google return woff2 files split by unicode-range
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"

README = """Fonts used by the site, self-hosted so pages don't depend on Google's servers.

  Inter           (c) The Inter Project Authors  https://github.com/rsms/inter
  IBM Plex Mono   (c) IBM Corp.                  https://github.com/IBM/plex

Both are licensed under the SIL Open Font License, Version 1.1:
https://openfontlicense.org  (full text: https://openfontlicense.org/open-font-license-official-text/)

Files come from Google Fonts, split by unicode-range (latin, latin-ext, greek).
Regenerate with: python scripts/fetch_fonts.py
"""


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def main():
    css = fetch(GOOGLE_URL).decode("utf-8")
    blocks = re.findall(r"/\* ([\w-]+) \*/\s*@font-face \{(.*?)\}", css, re.S)
    if not blocks:
        sys.exit("Could not read Google's font stylesheet")
    os.makedirs(FONT_DIR, exist_ok=True)

    files, rules = {}, []
    for subset, body in blocks:
        family = re.search(r"font-family: '([^']+)'", body).group(1)
        if subset not in KEEP.get(family, ()):
            continue
        style = re.search(r"font-style: (\w+);", body).group(1)
        weight = re.search(r"font-weight: (\d+);", body).group(1)
        src = re.search(r"url\(([^)]+)\)", body).group(1)
        urange = re.search(r"unicode-range: ([^;]+);", body).group(1).strip()
        if src not in files:
            slug = family.lower().replace(" ", "-")
            name = f"{slug}-{subset}.woff2" if family == "Inter" else f"{slug}-{weight}-{subset}.woff2"
            data = fetch(src)
            if data[:4] != b"wOF2":
                sys.exit(f"{src} is not a woff2 file")
            with open(os.path.join(FONT_DIR, name), "wb") as f:
                f.write(data)
            files[src] = name
            print(f"  saved assets/fonts/{name}  {len(data) / 1024:.1f} KB")
        rules.append(
            "@font-face {\n"
            f'  font-family: "{family}"; font-style: {style}; font-weight: {weight}; font-display: swap;\n'
            f'  src: url("/assets/fonts/{files[src]}") format("woff2");\n'
            f"  unicode-range: {urange};\n"
            "}"
        )

    with open(os.path.join(FONT_DIR, "README.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write(README)

    block = "/* FONTS:START - generated by scripts/fetch_fonts.py, do not edit by hand */\n" + "\n".join(rules) + "\n/* FONTS:END */"
    with open(CSS_PATH, encoding="utf-8") as f:
        text = f.read()
    pattern = re.compile(r"/\* FONTS:START.*?/\* FONTS:END \*/", re.S)
    if pattern.search(text):
        text = pattern.sub(lambda m: block, text, count=1)
    else:
        text = block + "\n\n" + text  # first run: the font rules go at the very top of the stylesheet
    with open(CSS_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"Wrote {len(rules)} @font-face rules into assets/css/style.css; {len(files)} font files in assets/fonts/")


if __name__ == "__main__":
    main()
